const translationCache = new Map();

export function getEntryTranslations(localeKey) {
  if (translationCache.has(localeKey)) {
    return translationCache.get(localeKey);
  }

  const localized = {};
  Object.entries(ENTRY_PAGE_TRANSLATIONS).forEach(([key, translations]) => {
    const segments = key.split('.');
    const leaf = segments.pop();
    let target = localized;

    segments.forEach((segment) => {
      target[segment] ??= {};
      target = target[segment];
    });

    target[leaf] = translations[localeKey];
  });

  translationCache.set(localeKey, localized);
  return localized;
}

export function fillTemplate(value, variables) {
  return Object.entries(variables).reduce(
    (output, [key, replacement]) => output.replaceAll('{' + key + '}', replacement),
    value,
  );
}
